# freeze_v2_1.py: writes LABEL_MAP_v2_1.json and FREEZE_v2_1.txt from the files as they actually are.
# Run after any accepted change to the v2.1 set. Stdlib only. Deterministic: same bytes in, same file out.
# arms_v2.json and mutation_items_v2.json here are byte-identical reference copies of the frozen v2 files (v2 itself is unchanged).
import hashlib
import json
import os
import platform
import sys

import labels

HERE = os.path.dirname(os.path.abspath(__file__))
ARTIFACTS = ["build_arms_v2_1.py", "build_items_v2_1.py", "scoring_v2.py", "test_v2_1.py", "test_checks_v2_1.py",
             "test_v2_1_fixes.py", "labels.py", "number_check.py", "mutation_set.py", "arm_check.py", "quote_check.py",
             "stability.py", "bearing_consistency.py", "signing.py", "freeze_v2_1.py", "test_freeze_v2_1.py",
             "verify_all_v2_1.py", "mutation_items_v2_1.json", "exclusions_v2_1.json", "arms_v2_1.json",
             "ARM_MANIFEST_v2_1.json", "passages_reconstructed.json", "claims_run12.json",
             "mutation_items_v2.json", "mutation_items_v1_no_second_refinery.json", "arms_v2.json", "README_v2_1.md", "LABEL_MAP_v2_1.json", "LICENSE", "NOTICE"]
RULES = [
    "a date range or day without a year is compared only with passage dates that carry a day or a month, never with a bare year; if month/day agree but only one side states the year the result is YEAR_UNSTATED, not MATCH (v2.1 r2, after review of 08 Nov 2026)",
    "a missing answer (no output, N/A, arm not built) is NOT a label change: stability counts it as absent, not as flipped (v2.1: stability.cells now does what v2 only said)",
    "UNTESTED (the judge answered, code removed the answer) is its own label: no verdict, no stability flip, and every rate is reported over all rows AND over judged rows",
    "an arm whose evidence text equals the A arm's evidence text is invalid by construction (test_v2_1 asserts it)",
    "F and G must come from a different passage than the claim, and must share no MATCH with the claim, dates without a year included (test_v2_1 asserts it)",
    "C and C_num keep the source string of A; length within 5 % (test_v2_1 asserts it)",
    "REFUTED on F/G is acceptable only where arm_check.expected_on_unrelated says REFUTED_ADMISSIBLE",
    "the anchor claim c10.s0.identity (prose without a number) is excluded from accuracy in every arm",
    "J_gate is a gate, not a metric: never report it without Acc(A) per subclass and both FDR_neg components",
    "every mutation candidate leaves a trace: kept/dropped items carry status and reason; candidates without a variant are in exclusions_v2_1.json with a reason",
    "v2 files (arms_v2.json, mutation_items_v2.json and the whole null-arm-checks-v2 folder) are not changed by v2.1",
]


def sha(name):
    return hashlib.sha256(open(os.path.join(HERE, name), "rb").read()).hexdigest()


def cr_count(name):
    return open(os.path.join(HERE, name), "rb").read().count(b"\r")


def write_label_map():
    doc = {
        "version": "v2.1-draft",
        "scale": [labels.SUP, labels.REF, labels.NEI, labels.REFUSAL, labels.UNTESTED],
        "aliases": {k: labels._ALIASES[k] for k in sorted(labels._ALIASES)},
        "decisions": {
            "NEEDS_RECOVERY": {"mapped_to": labels.NEI,
                               "reason": "in supplied-evidence mode there is no second search, so a number "
                                         "the source does not carry is missing information, not a declined task",
                               "sensitivity_switch": "python3 scoring_v2.py --needs-recovery refusal"},
            "NO_NUMBERS": {"mapped_to": labels.REFUSAL,
                            "reason": "scope exclusion by the pre-model filter, not a verdict on evidence"},
            "UNT / UNTESTED": {"mapped_to": labels.UNTESTED,
                                "reason": "v2.1: the judge answered and code removed the answer; not a refusal and not a verdict. "
                                          "v2 mapped it to REFUSAL, which put these rows inside the judged denominators"},
        },
        "unmapped_behaviour": "norm() returns the string unchanged; an unmapped label is a defect, not a fallback",
    }
    with open(os.path.join(HERE, "LABEL_MAP_v2_1.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=1, sort_keys=True)
        fh.write("\n")


def write_freeze():
    lines = [
        "# FREEZE — arm set v2.1 DRAFT, regenerated by freeze_v2_1.py. Not a joint freeze until the other party agrees.",
        "# If a hash differs, the file is not the one reviewed. Re-run: python3 freeze_v2_1.py",
        "",
        "## environment (portable part only; the machine this was generated on is in ENVIRONMENT_v2_1.txt, not hashed)",
        "dependencies: standard library only",
        "line endings: LF (CR bytes measured per artifact, all zero)",
        "locale note: run with PYTHONIOENCODING=utf-8 and -X utf8 on Windows",
        "",
        "## rules that scoring depends on",
    ]
    lines += [f"- {r}" for r in RULES]
    lines += ["", "## artifacts"]
    for name in ARTIFACTS:
        path = os.path.join(HERE, name)
        if not os.path.exists(path):
            lines.append(f"MISSING  {name}")
            continue
        lines.append(f"{sha(name)}  {name}  (bytes {os.path.getsize(path)}, lines {len(open(path,'rb').read().splitlines())}, CR {cr_count(name)})")
    with open(os.path.join(HERE, "ENVIRONMENT_v2_1.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(f"generated on: {platform.system()} {platform.release()} ({platform.machine()})\npython: {sys.version.split()[0]}\n"
                 "informational only: nothing verifies this file, it is outside the frozen bytes\n")
    with open(os.path.join(HERE, "FREEZE_v2_1.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    write_label_map()
    write_freeze()
    print("LABEL_MAP_v2_1.json and FREEZE_v2_1.txt rewritten from the actual files")
