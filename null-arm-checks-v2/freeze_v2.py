# freeze_v2.py: writes LABEL_MAP_v2.json and FREEZE_v2.txt from the files as they actually are.
# Run after any accepted change to the set. Stdlib only. Deterministic: same bytes in, same file out.
import hashlib
import json
import os
import platform
import sys

import labels

HERE = os.path.dirname(os.path.abspath(__file__))
ARTIFACTS = ["build_arms_v2.py", "scoring_v2.py", "test_v2.py", "test_checks.py", "labels.py",
             "number_check.py", "mutation_set.py", "arm_check.py", "quote_check.py",
             "stability.py", "bearing_consistency.py", "signing.py", "freeze_v2.py",
             "test_freeze.py", "verify_all.py",
             "mutation_items_v2.json", "passages_reconstructed.json", "claims_run12.json",
             "arms_v2.json", "ARM_MANIFEST_v2.json", "README_v2.md", "DRAFT_NOTES_v3.md",
             "LABEL_MAP_v2.json", "LICENSE", "NOTICE"]
RULES = [
    "a missing answer (no output, N/A, arm not built) is NOT a label change: stability counts it as absent, not as flipped",
    "an arm whose evidence text equals the A arm's evidence text is invalid by construction (test_v2 asserts it)",
    "F and G must come from a different passage than the claim (test_v2 asserts it)",
    "C and C_num keep the source string of A; length within 5 % (test_v2 asserts it)",
    "REFUTED on F/G is acceptable only where arm_check.expected_on_unrelated says REFUTED_ADMISSIBLE",
    "the anchor claim c10.s0.identity (prose without a number) is excluded from accuracy in every arm",
    "J_gate is a gate, not a metric: never report it without Acc(A) per subclass and both FDR_neg components",
]


def sha(name):
    return hashlib.sha256(open(os.path.join(HERE, name), "rb").read()).hexdigest()


def cr_count(name):
    return open(os.path.join(HERE, name), "rb").read().count(b"\r")


def write_label_map():
    doc = {
        "version": "v2-draft",
        "scale": [labels.SUP, labels.REF, labels.NEI, labels.REFUSAL],
        "aliases": {k: labels._ALIASES[k] for k in sorted(labels._ALIASES)},
        "decisions": {
            "NEEDS_RECOVERY": {"mapped_to": labels.NEI,
                               "reason": "in supplied-evidence mode there is no second search, so a number "
                                         "the source does not carry is missing information, not a declined task",
                               "sensitivity_switch": "python3 scoring_v2.py --needs-recovery refusal",
                               "measured_effect": "on our draft manifest the switch moves 52 refusal-only cells "
                                                  "and changes neither Acc_A, FDR_neg nor J_gate; on the frozen v1 "
                                                  "manifest it moves 0 cells"},
            "NO_NUMBERS": {"mapped_to": labels.REFUSAL,
                            "reason": "scope exclusion by the pre-model filter, not a verdict on evidence"},
            "UNT / UNTESTED": {"mapped_to": labels.REFUSAL, "reason": "the judge's own refusal status"},
        },
        "unmapped_behaviour": "norm() returns the string unchanged; an unmapped label is a defect, not a fallback",
    }
    with open(os.path.join(HERE, "LABEL_MAP_v2.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=1, sort_keys=True)
        fh.write("\n")


def write_freeze():
    lines = [
        "# FREEZE — arm set v2 DRAFT, regenerated by freeze_v2.py. Not a joint freeze until the other party agrees.",
        "# If a hash differs, the file is not the one reviewed. Re-run: python3 freeze_v2.py",
        "",
        "## environment",
        f"os: {platform.system()} {platform.release()} ({platform.machine()})",
        f"python: {sys.version.split()[0]}",
        "dependencies: standard library only",
        "line endings: LF (CR bytes measured per artifact, all zero)",
        "locale note: run with PYTHONIOENCODING=utf-8 and -X utf8 on Windows",
        "",
        "## rules that scoring depends on",
    ]
    lines += [f"- {r}" for r in RULES]
    lines += ["", "## artifacts"]
    for name in ARTIFACTS:
        path = os.path.join(HERE, name)
        if not os.path.exists(path):
            lines.append(f"MISSING  {name}")
            continue
        lines.append(f"{sha(name)}  {name}  (bytes {os.path.getsize(path)}, lines {len(open(path,'rb').read().splitlines())}, CR {cr_count(name)})")
    with open(os.path.join(HERE, "FREEZE_v2.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    write_label_map()
    write_freeze()
    print("LABEL_MAP_v2.json и FREEZE_v2.txt перезаписаны по фактическому состоянию")
